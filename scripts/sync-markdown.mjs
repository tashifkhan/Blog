#!/usr/bin/env bun
/**
 * Mirror packages/markdown/ into the build roots that cannot import across a
 * directory boundary.
 *
 * The editor's Docker build context is `editor/` alone, and tashif.codes is a
 * separate repository, so a shared path or a workspace dependency is not
 * available to either. Copies are generated rather than hand-maintained, and
 * `--check` fails on drift so a mirror cannot quietly fall behind.
 *
 *   bun scripts/sync-markdown.mjs
 *   bun scripts/sync-markdown.mjs ../tashif.codes/src/lib/markdown
 *   bun scripts/sync-markdown.mjs --check ../tashif.codes/src/lib/markdown
 */

import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = join(ROOT, 'packages/markdown')
const DEFAULT_TARGETS = [join(ROOT, 'editor/src/markdown')]

/** Files that stay in the canonical copy only. */
const SKIP = new Set(['README.md'])
const SKIP_SUFFIX = ['.test.ts']

const BANNER = (name) =>
  `/* Generated by scripts/sync-markdown.mjs from packages/markdown/${name}.\n * Edit the canonical copy, then re-run the sync. */\n`

function isSkipped(name) {
  return SKIP.has(name) || SKIP_SUFFIX.some((suffix) => name.endsWith(suffix))
}

/**
 * Mark a mirrored file as generated. TypeScript and CSS share block-comment
 * syntax, so one banner covers every file this script copies.
 */
function withBanner(name, contents) {
  if (name.endsWith('.ts') || name.endsWith('.css')) {
    return BANNER(name) + contents
  }
  return contents
}

async function main() {
  const args = process.argv.slice(2)
  const check = args.includes('--check')
  const extra = args.filter((arg) => !arg.startsWith('--'))
  const targets = [
    ...DEFAULT_TARGETS,
    ...extra.map((path) => resolve(process.cwd(), path)),
  ]

  const names = (await readdir(SOURCE)).filter((name) => !isSkipped(name)).sort()
  const files = new Map()
  for (const name of names) {
    files.set(name, await readFile(join(SOURCE, name), 'utf8'))
  }

  let drifted = 0

  for (const target of targets) {
    for (const [name, contents] of files) {
      const expected = withBanner(name, contents)
      const destination = join(target, name)

      if (check) {
        let actual = null
        try {
          actual = await readFile(destination, 'utf8')
        } catch {
          // Missing counts as drift.
        }
        if (actual !== expected) {
          drifted++
          console.error(
            `drift: ${relative(process.cwd(), destination)}${actual === null ? ' (missing)' : ''}`,
          )
        }
        continue
      }

      await mkdir(dirname(destination), { recursive: true })
      await writeFile(destination, expected)
    }

    if (!check) {
      console.log(`synced ${files.size} files -> ${relative(process.cwd(), target)}`)
    }
  }

  if (check) {
    if (drifted) {
      console.error(
        `\n${drifted} file(s) out of sync. Run: bun scripts/sync-markdown.mjs ${extra.join(' ')}`,
      )
      process.exit(1)
    }
    console.log('markdown mirrors are in sync')
  }
}

await main()
